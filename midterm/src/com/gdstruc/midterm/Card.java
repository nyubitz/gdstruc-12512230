package com.gdstruc.midterm;

import java.util.Objects;

public class Card {
    private int id;
    private String name;
    private int index;

    public Card(int id, String name){
        this.id = id;
        this.name = name;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getIndex() {
        return index;
    }

    public void setIndex(int index) {
        this.index = index;
    }

    @Override
    public String toString() {
        return name + " (ID: " + id + ")";
    }
}
